const translations: Record<Lang, Dict> = { en, lt };

const STORAGE_KEY = 'hb_lang';

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: 'en',
  setLang: () => {},
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  // Start with 'en' on both server and client so hydration matches, then read
  // the stored/browser preference after mount.
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'lt' || stored === 'en') setLangState(stored);
      else if (navigator.language?.toLowerCase().startsWith('lt')) setLangState('lt');
    } catch { /* localStorage unavailable — stay on default */ }
  }, []);

  function setLang(l: Lang) {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* ignore */ }
  }

  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useLang(): { lang: Lang; setLang: (l: Lang) => void; t: Dict } {
  const { lang, setLang } = useContext(LangContext);
  return { lang, setLang, t: translations[lang] };
}

/** EN | LT switcher. Reuses portal button styles so it fits anywhere. */
export function LangToggle({ style }: { style?: React.CSSProperties }) {
  const { lang, setLang } = useLang();
  return (
    <div className="hb-segment" style={{ display: 'inline-flex', gap: 4, ...style }}>
      {(['en', 'lt'] as const).map(l => (
        <button
          key={l}
          type="button"
          className={`hb-btn sm${lang === l ? ' selected' : ''}`}
          onClick={() => setLang(l)}
          aria-pressed={lang === l}
        >
          {l.toUpperCase()}
        </button>
      ))}
    </div>
  );
}
