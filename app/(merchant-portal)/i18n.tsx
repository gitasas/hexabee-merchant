/** Lithuanian plural forms: [1 mokėjimas, 2–9 mokėjimai, 10–20/0 mokėjimų]. */
function ltPlural(n: number, forms: [string, string, string]): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 9 && !(mod100 >= 11 && mod100 <= 19)) return forms[1];
  return forms[2];
}

